package me.rerere.rikkahub.data.workspace

import me.rerere.workspace.RootfsPatchOptions
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File

class WorkspaceEnvironmentMaintenanceTest {

    @get:Rule
    val temporaryFolder = TemporaryFolder()

    @Test
    fun `shared candidate replaces installer default dns with app dns`() {
        val candidate = temporaryFolder.newFolder("candidate-custom-dns")
        val resolvConf = File(candidate, "etc/resolv.conf").apply {
            parentFile.mkdirs()
            writeText(
                """# Generated by 黑猫ai workspace.
                    |nameserver 1.1.1.1
                    |nameserver 8.8.8.8
                    |nameserver 223.5.5.5
                    |options edns0 trust-ad
                    |""".trimMargin()
            )
        }

        patchSharedRootfsCandidate(
            candidate,
            RootfsPatchOptions(nameservers = listOf("10.0.0.53", "10.0.0.54")),
        )

        val patched = resolvConf.readText()
        assertTrue(patched.contains("nameserver 10.0.0.53"))
        assertTrue(patched.contains("nameserver 10.0.0.54"))
        assertTrue(!patched.contains("nameserver 1.1.1.1"))
    }

    @Test
    fun `shared candidate preserves distribution dns`() {
        val candidate = temporaryFolder.newFolder("candidate-existing-dns")
        val resolvConf = File(candidate, "etc/resolv.conf").apply {
            parentFile.mkdirs()
            writeText("nameserver 192.0.2.53\n")
        }

        patchSharedRootfsCandidate(
            candidate,
            RootfsPatchOptions(nameservers = listOf("10.0.0.53")),
        )

        assertEquals("nameserver 192.0.2.53\n", resolvConf.readText())
    }
}
